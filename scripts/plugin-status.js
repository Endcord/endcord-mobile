#!/usr/bin/env node
/*
 * Builds docs/plugins/README.md: an overview of what happened to every Endcord PC plugin on mobile,
 * collected from the per-batch tables in docs/plugins/*.md.
 *
 *   node scripts/plugin-status.js
 */
"use strict";

const fs = require("fs");
const path = require("path");

const dir = path.resolve(__dirname, "..", "docs", "plugins");
const rows = [];
for (const file of fs.readdirSync(dir).filter(f => /^\d\d-.*\.md$/.test(f)).sort()) {
    for (const line of fs.readFileSync(path.join(dir, file), "utf8").split("\n")) {
        const cells = line.split("|").map(c => c.trim());
        // | Plugin | Status | Notes |
        if (cells.length < 4 || cells[1] === "Plugin" || /^-+$/.test(cells[1]) || !cells[1]) continue;
        rows.push({ plugin: cells[1].replace(/`/g, ""), status: cells[2], file });
    }
}

const order = ["Ported", "Partial", "Not applicable", "Skipped"];
const norm = s => order.find(o => s.toLowerCase().startsWith(o.toLowerCase())) || s;
const counts = {};
for (const r of rows) counts[norm(r.status)] = (counts[norm(r.status)] || 0) + 1;

let out = "# Endcord PC plugins on mobile\n\n";
out += "Generated by `node scripts/plugin-status.js` from the batch tables in this folder, which explain every decision.\n\n";
out += "| Status | Plugins |\n| --- | --- |\n";
for (const s of order) out += `| ${s} | ${counts[s] || 0} |\n`;
out += `| **Total** | **${rows.length}** |\n\n`;
out += "**Ported** works like on PC. **Partial** works, with the mobile differences noted. **Not applicable** can't exist on the\n";
out += "legacy Android app (desktop, keyboard, mouse or Electron features). **Skipped** was left out on purpose, with the reason.\n\n";
out += "| Plugin | Status | Details |\n| --- | --- | --- |\n";
for (const r of rows.sort((a, b) => a.plugin.localeCompare(b.plugin))) {
    out += `| ${r.plugin} | ${norm(r.status)} | [${r.file.replace(".md", "")}](${r.file}) |\n`;
}
fs.writeFileSync(path.join(dir, "README.md"), out);
console.log(rows.length, "plugins:", JSON.stringify(counts));
