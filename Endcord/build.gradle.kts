/**
 * Compiles the translation tables in `i18n/` into Kotlin, since the core is shipped as a bare dex without
 * any java resources. Each table becomes a few string constants that `I18n` parses lazily on first use.
 */
abstract class GenerateI18nTask : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val sourceDir: DirectoryProperty

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val kinds = linkedMapOf("CORE" to "core", "PLUGINS" to "plugins")
        val languages = listOf("tr", "ru", "es", "fr")
        val out = StringBuilder()
        out.append("// Generated by :Endcord:generateI18n from i18n/*.json. Do not edit.\n")
        out.append("package com.aliucord.i18n\n\n")
        out.append("internal object I18nData {\n")
        kinds.keys.forEachIndexed { i, kind -> out.append("    const val $kind = $i\n") }
        out.append("\n    @JvmStatic\n    fun chunks(lang: String, kind: Int): Array<String> = when (kind) {\n")
        for ((kind, dir) in kinds) {
            out.append("        $kind -> when (lang) {\n")
            for (lang in languages) out.append("            \"$lang\" -> ${dir}_$lang()\n")
            out.append("            else -> emptyArray()\n        }\n")
        }
        out.append("        else -> emptyArray()\n    }\n")

        // Translations of the built-in plugins live in per-batch files shaped { "English": { "tr": "...", ... } }
        val batchFiles = sourceDir.dir("batches").get().asFile.listFiles { f -> f.name.endsWith(".json") }
            ?.sortedBy { it.name }.orEmpty()
        @Suppress("UNCHECKED_CAST")
        val batches = batchFiles.map { groovy.json.JsonSlurper().parse(it, "UTF-8") as Map<String, Map<String, Any?>> }

        for ((_, dir) in kinds) for (lang in languages) {
            val file = sourceDir.file("$dir/$lang.json").get().asFile
            @Suppress("UNCHECKED_CAST")
            val table = LinkedHashMap<String, Any?>()
            for (batch in batches) {
                if (dir != "core") break
                for ((english, byLang) in batch) byLang[lang]?.let { table.putIfAbsent(english, it) }
            }
            // The main tables win over batch files
            if (file.exists()) table.putAll(groovy.json.JsonSlurper().parse(file, "UTF-8") as Map<String, Any?>)
            val chunks = mutableListOf<StringBuilder>()
            var current = StringBuilder()
            var bytes = 0
            for ((key, value) in table.toSortedMap()) {
                if (value == null || value.toString().isEmpty()) continue
                val record = escape(key) + "\\u0001" + escape(value.toString()) + "\\u0002"
                val size = record.toByteArray(Charsets.UTF_8).size
                if (bytes + size > 40_000 && current.isNotEmpty()) {
                    chunks += current
                    current = StringBuilder()
                    bytes = 0
                }
                current.append(record)
                bytes += size
            }
            if (current.isNotEmpty()) chunks += current
            out.append("\n    private fun ${dir}_$lang(): Array<String> = arrayOf(\n")
            for (chunk in chunks) out.append("        \"").append(chunk).append("\",\n")
            out.append("    )\n")
        }
        out.append("}\n")

        val target = outputDir.file("com/aliucord/i18n/I18nData.kt").get().asFile
        target.parentFile.mkdirs()
        target.writeText(out.toString(), Charsets.UTF_8)
    }

    private fun escape(s: String): String = buildString(s.length + 8) {
        for (c in s) when {
            c == '\\' -> append("\\\\")
            c == '"' -> append("\\\"")
            c == '$' -> append("\\$")
            c == '\n' -> append("\\n")
            c == '\r' -> append("\\r")
            c == '\t' -> append("\\t")
            c.code < 0x20 || c.code == 0x7f || c.isSurrogate() -> append("\\u%04x".format(c.code))
            else -> append(c)
        }
    }
}

val generateI18n = tasks.register<GenerateI18nTask>("generateI18n") {
    sourceDir.set(layout.projectDirectory.dir("i18n"))
    outputDir.set(layout.buildDirectory.dir("generated/source/i18n"))
}

androidComponents {
    onVariants { variant ->
        variant.sources.java?.addGeneratedSourceDirectory(generateI18n, GenerateI18nTask::outputDir)
    }
}

